#!/usr/bin/env python3
"""
analysis/maintenance/checksums.py
==============================================================================
SHA-256 checksum list of the run artefacts (checkpoints, hparams, metrics) and its verification
==============================================================================

``runs/`` is not tracked by git (it is distributed as an archive, ``runs/README.md``).  This script
writes ``docs/checksums.sha256`` -- one ``<sha256>  <path relative to the repository root>`` line
per file -- for

* every ``*.ckpt`` under ``runs/`` (the best-epoch checkpoints quoted in the reports and the few
  ``last*.ckpt`` files of interrupted runs),
* every ``hparams.yaml`` and ``metrics/*.json`` / ``experiment_state.json`` under ``runs/``,
* the tracked E-PANNs initialisation ``semantic_backbone/epanns/checkpoint_closeto_.44.pt``,

and verifies a restored archive with ``--verify`` (exit code 1 on any mismatch or missing file).

Usage
-----
    python analysis/maintenance/checksums.py            # write docs/checksums.sha256
    python analysis/maintenance/checksums.py --verify   # compare the files on disk with the list

Author
------
Stefano Giacomelli, Ph.D. candidate
DISIM Department — University of L'Aquila
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path
from typing import Dict, List

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "checksums.sha256"
EXTRA = [ROOT / "semantic_backbone" / "epanns" / "checkpoint_closeto_.44.pt"]


def sha256(path: Path, block: int = 1 << 24) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        while True:
            chunk = fh.read(block)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()


def artefacts() -> List[Path]:
    runs = ROOT / "runs"
    files: List[Path] = []
    if runs.exists():
        files += sorted(runs.rglob("*.ckpt"))
        files += sorted(runs.rglob("hparams.yaml"))
        files += sorted(runs.glob("*/*/metrics/*.json"))
        files += sorted(runs.glob("*/metrics/*.json"))
        files += sorted(runs.glob("*/experiment_state.json"))
        files += sorted(runs.glob("*/*/experiment_state.json"))
    files += [p for p in EXTRA if p.exists()]
    seen, out = set(), []
    for p in files:
        if p not in seen:
            seen.add(p)
            out.append(p)
    return out


def read_list(path: Path) -> Dict[str, str]:
    table: Dict[str, str] = {}
    for line in path.read_text().splitlines():
        if line.strip() and not line.startswith("#"):
            digest, name = line.split("  ", 1)
            table[name] = digest
    return table


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("Usage")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--verify", action="store_true")
    ap.add_argument("--list", type=Path, default=OUT)
    args = ap.parse_args()
    if args.verify:
        table = read_list(args.list)
        bad = 0
        for name, digest in table.items():
            p = ROOT / name
            if not p.exists():
                print(f"MISSING  {name}")
                bad += 1
            elif sha256(p) != digest:
                print(f"MISMATCH {name}")
                bad += 1
        print(f"{len(table)} files checked, {bad} problem(s)")
        sys.exit(1 if bad else 0)
    files = artefacts()
    lines = [
        "# SHA-256 of the run artefacts of spatial_gpat (checkpoints, hparams, metrics, E-PANNs init).",
        "# Generated by analysis/maintenance/checksums.py; verify a restored runs/ archive with --verify.",
    ]
    for p in files:
        lines.append(f"{sha256(p)}  {p.relative_to(ROOT)}")
        print(".", end="", flush=True)
    args.list.parent.mkdir(parents=True, exist_ok=True)
    args.list.write_text("\n".join(lines) + "\n")
    print(f"\n{len(files)} files -> {args.list}")


if __name__ == "__main__":
    main()
